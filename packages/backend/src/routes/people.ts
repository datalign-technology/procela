/** DELETE /api/v1/people/:id */
router.delete('/:id', async (req: Request, res: Response) => {
  const person = await peopleRepo.get(String(req.params.id));
  if (!person) { res.status(404).json({ success: false, error: 'Person not found' }); return; }
  const personId = person.id;

  // Cascade: any ACTIVE agent that lists this person as its
  // responsible party is auto-paused, and an ownership issue opens.
  // We clear the dangling ownerPersonId reference on the paused agents
  // too — leaving it pointing at a deleted person would trip the
  // "unknown person" fallback in every list view.
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const { pauseAgentsForMissingOwner } = require('./agents') as typeof import('./agents');
  const pausedAgents = await pauseAgentsForMissingOwner(
    personId,
    'Responsible person was deleted',
    { clearOwnerReference: true },
  );

  await peopleRepo.delete(personId);

  // 204 has no body, so switch to 200 when the cascade produced work
  // the caller needs to know about (frontend uses this to render a
  // toast + linked list of paused agents).
  if (pausedAgents.length > 0) {
    res.json({ success: true, cascade: { pausedAgents } });
    return;
  }
  res.status(204).send();
});

/**
 * POST /api/v1/people/:id/forget
 * Body: { confirm: "FORGET <email>" }
 *
 * The GDPR Article 17 cascade — "right to be forgotten". Removes the
 * person record, scrubs every reference to them across the data
 * stores (ownership, stewardship, group membership, authored
 * comments), and tombstones their entries in the audit log so the
 * action history survives but the personal identifier doesn't.
 *
 * Confirmation gate: the request body must include `confirm` set to
 * the literal string `FORGET <email>` to defend against accidental
 * triggers. Without this an admin clicking "Forget" by mistake could
 * cascade an irreversible delete across the catalog.
 *
 * Returns a summary of the sweep so the admin sees the blast radius.
 * Pair with a server restart in production — in-memory store copies
 * in route modules don't pick up the on-disk scrub until reload.
 */
router.post('/:id/forget', async (req: Request, res: Response) => {
  const person = await peopleRepo.get(String(req.params.id));
  if (!person) { res.status(404).json({ success: false, error: 'Person not found' }); return; }

  const confirmExpected = `FORGET ${person.email}`;
  if ((req.body?.confirm || '') !== confirmExpected) {
    res.status(400).json({
      success: false,
      error: `Confirmation phrase did not match. Pass { confirm: "${confirmExpected}" } to proceed.`,
    });
    return;
  }

  // Remove the person record on disk first so the cascade's
  // reloadAllStores() pass picks up the deletion uniformly with
  // every other scrubbed store. Order matters: cascade runs after
  // the people file is rewritten so the reload-from-disk pass at
  // the end of the cascade sees a consistent snapshot.
  await peopleRepo.delete(person.id);

  // Lazy import to break the route ↔ service circular dependency.
  // The gdpr service imports auditService which doesn't depend on
  // routes; importing it at top-level is fine, but require() keeps
  // the dep graph easy to reason about for someone reading the
  // delete handler cold.
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const { erasePersonReferences } = require('../services/gdpr.service') as typeof import('../services/gdpr.service');
  const report = erasePersonReferences(person.id);

  res.json({
    success: true,
    data: {
      personId: person.id,
      email: person.email,
      cascadeReport: report,
      message: report.storesReloaded.length > 0
        ? `Person record erased and references scrubbed across stores. ${report.storesReloaded.length} in-memory stores were reloaded automatically.`
        : 'Person record erased and references scrubbed across stores. Restart the server to flush any cached in-memory copies in long-lived route modules.',
    },
  });
});

/** POST /api/v1/people/:id/deactivate
 *  Soft-delete. The person stays in the store (preserves audit trail,
 *  authored comments, role-assignment history) but can't sign in and
 *  doesn't appear in the default People list. Reverse with the
 *  /reactivate endpoint below. */
router.post('/:id/deactivate', async (req: Request, res: Response) => {
  const person = await peopleRepo.get(String(req.params.id));
  if (!person) { res.status(404).json({ success: false, error: 'Person not found' }); return; }
  if (person.active === false) {
    res.json({ success: true, data: publicPerson(person), message: 'Already deactivated' });
    return;
  }
  person.active = false;
  person.deactivatedAt = new Date().toISOString();
  person.updatedAt = person.deactivatedAt;
  await peopleRepo.update(person.id, person);

  // Cascade: a deactivated person is no longer a valid responsible
  // party. Any ACTIVE agent they own auto-pauses (owner reference is
  // preserved — reactivation should be able to restore the pairing
  // even if it doesn't auto-resume the agent).
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const { pauseAgentsForMissingOwner } = require('./agents') as typeof import('./agents');
  const pausedAgents = await pauseAgentsForMissingOwner(
    person.id,
    'Responsible person was deactivated',
    { clearOwnerReference: false },
  );

  res.json({ success: true, data: publicPerson(person), cascade: { pausedAgents } });
});


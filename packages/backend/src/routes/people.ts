export interface StoredPerson {
  id: string;
  orgIds: string[];
  accessibleOrgIds: string[];
  name: string;
  email: string;
  /** Default / fallback role used when the active org does not have a
   *  per-org override in orgRoles. A holdover from the single-role
   *  model; new installs should set per-org roles instead, but the
   *  fallback keeps every existing record valid. */
  role: string;
  /** Per-org role overrides. Empty / absent → person.role applies in
   *  every assigned org. When an entry matches the active org, its
   *  role wins. Useful when one person is a process owner in
   *  Operations but a viewer in Finance. */
  orgRoles?: Array<{ orgId: string; role: string }>;
  title: string;
  jobRole?: string;
  skillIds: string[];
  /** Argon2id hash of the user's local password. Only present when
   *  the Local auth provider has been set up for this person. OIDC /
   *  SAML / Dev users never carry a hash — login federates to the IdP
   *  or skips credentials entirely. The hash MUST be stripped from
   *  every API response that surfaces a person record; see
   *  publicPerson() below. */
  passwordHash?: string;
  /** ISO timestamp of the last password change. Drives audit + the
   *  forced-rotation check on first login after an admin reset. */
  passwordUpdatedAt?: string;
  /** When true, the user's current password was set by an admin or
   *  the dev→local migration and must be changed before the user can
   *  do anything else. The login flow short-circuits to a "set new
   *  password" prompt instead of issuing a normal session. */
  passwordMustChange?: boolean;
  /** Counter for consecutive failed login attempts. Reset on success.
   *  Drives the lockout: when failedLoginCount crosses the threshold
   *  inside the rolling window starting at failedLoginFirstAt, the
   *  account is locked via lockedUntil. */
  failedLoginCount?: number;
  failedLoginFirstAt?: string;
  /** ISO timestamp of when the account becomes signable-in-able again.
   *  Login is rejected until now > lockedUntil; the value is then
   *  cleared on the next attempt regardless of outcome so the failure
   *  counter starts fresh. */
  lockedUntil?: string;
  /** Base32-encoded TOTP secret. Present once the user has scanned
   *  the QR and verified a code; absent before enrollment and after
   *  disable / admin-reset. SHOULD be encrypted at rest in
   *  production — Argon2 doesn't apply (the server has to compute
   *  HMAC against the raw bytes), so this needs a column-level KMS
   *  layer when Postgres lands. Stripped from every API response
   *  via publicPerson(). */
  mfaSecret?: string;
  /** True once enrollment is verified end-to-end (the user proved
   *  they can produce a code from the secret). The login flow checks
   *  this flag, not just presence of mfaSecret, so partial enrollment
   *  doesn't lock a user out. */
  mfaEnrolled?: boolean;
  /** Argon2id hashes of single-use backup codes. Generated at
   *  enrollment, shown to the user once, hashed for storage. Removed
   *  on use; regenerated by an admin reset. */
  mfaBackupCodes?: string[];
  /** Registered WebAuthn / FIDO2 credentials. A user can have many
   *  — a YubiKey, a phone fingerprint, a laptop's platform key.
   *  Either WebAuthn OR TOTP satisfies the MFA gate at login; users
   *  can configure both. credentialID and publicKey are base64url
   *  binary; counter is the per-credential replay counter the
   *  authenticator increments on each use. */
  webauthnCredentials?: Array<{
    id: string;             // internal handle (uuid)
    credentialID: string;   // base64url, returned by the authenticator
    publicKey: string;      // base64url, COSE-encoded
    counter: number;        // replay counter, expected to monotonically increase
    transports?: string[];  // e.g. ['internal','hybrid','usb']
    label: string;          // user-supplied: "YubiKey 5", "iPhone Touch ID"
    createdAt: string;
  }>;
  /** Soft-delete flag. Absent or true → the person can sign in and
   *  appears in default list views. False → the person is preserved
   *  for audit but cannot authenticate, doesn't appear in default
   *  lists, and is exposed to SCIM as active=false. Set by SCIM PUT /
   *  PATCH with active=false (the standard offboarding signal IdPs
   *  send) and by the admin "Deactivate" action. Reactivation just
   *  flips the flag back. SCIM DELETE still hard-deletes — explicit
   *  is explicit. */
  active?: boolean;
  /** Timestamp of the active=false transition. Lets the People page
   *  show "Deactivated 12 days ago" and audit reports surface
   *  recently-disabled accounts. */
  deactivatedAt?: string;
  createdAt: string;
  updatedAt: string;
}

/** A person is "active" when the flag is absent OR true. Existing
 *  records predate the field; treating absence as active is the
 *  only safe back-compat read. */
export function isActive(p: StoredPerson): boolean {
  return p.active !== false;
}

/** Strip credential fields from a person record before sending over
 *  the wire. Every read path that returns people MUST use this; the
 *  raw StoredPerson is internal-only.
 *
 *  Strips:
 *    - passwordHash         the Argon2 password hash
 *    - mfaSecret            the TOTP secret (HMAC key — server-side
 *                           only)
 *    - mfaBackupCodes       the Argon2 hashes of single-use codes
 *
 *  Surfaces:
 *    - mfaEnrolled (bool)   so the frontend knows whether to show
 *                           "Enrolled" vs "Set up" in Settings. */
export type PublicPerson = Omit<StoredPerson, 'passwordHash' | 'mfaSecret' | 'mfaBackupCodes' | 'webauthnCredentials' | 'failedLoginCount' | 'failedLoginFirstAt' | 'lockedUntil'> & {
  /** Public-safe representation of WebAuthn credentials — just the
   *  metadata the user / admin should see (which keys are
   *  registered, when, with what label). Credential ID and public
   *  key stay server-side. */
  webauthnCredentials?: Array<{ id: string; label: string; createdAt: string; transports?: string[] }>;
  webauthnEnrolled?: boolean;
  /** True when the account is currently locked by the brute-force
   *  protection. Surfaced so the admin SecurityCard can show a
   *  "Locked" pill and a one-click clear button without leaking the
   *  raw failure counter / window-start timestamp. */
  locked?: boolean;
  lockedUntil?: string;
};

export function publicPerson(p: StoredPerson): PublicPerson {
  const {
    passwordHash, mfaSecret, mfaBackupCodes, webauthnCredentials,
    failedLoginCount, failedLoginFirstAt, lockedUntil,
    ...rest
  } = p;
  void passwordHash; void mfaSecret; void mfaBackupCodes;
  void failedLoginCount; void failedLoginFirstAt;
  const lockedUntilMs = lockedUntil ? new Date(lockedUntil).getTime() : 0;
  const isLocked = Number.isFinite(lockedUntilMs) && lockedUntilMs > Date.now();
  return {
    ...rest,
    webauthnEnrolled: (webauthnCredentials?.length || 0) > 0,
    ...(webauthnCredentials?.length
      ? { webauthnCredentials: webauthnCredentials.map((c) => ({ id: c.id, label: c.label, createdAt: c.createdAt, transports: c.transports })) }
      : {}),
    ...(isLocked ? { locked: true, lockedUntil } : {}),
  };
}

// ── Org access resolution ──

export function getDescendantOrgIds(orgId: string): string[] {
  const organizations = getCachedOrgList();
  const ids: string[] = [];
  const children = organizations.filter((o) => o.parentId === orgId);
  for (const child of children) {
    ids.push(child.id);
    ids.push(...getDescendantOrgIds(child.id));
  }
  return ids;
}

function getAncestorOrgs(orgId: string, levels: string[]): string[] {
  const organizations = getCachedOrgList();
  const ids: string[] = [];
  let current = organizations.find((o) => o.id === orgId);
  while (current?.parentId) {
    const parent = organizations.find((o) => o.id === current!.parentId);
    if (!parent) break;
    if (levels.includes(parent.type)) ids.push(parent.id);
    current = parent;
  }
  return ids;
}

const WORKING_LEVELS = ['company', 'division'];

/** Resolve the effective role for a person when acting inside a
 *  specific org. Per-org overrides win; otherwise the person.role
 *  fallback applies. SUPER_ADMIN never gets downgraded by an entry —
 *  if a record somehow carries an orgRoles entry that demotes a
 *  super-admin, we ignore it (defence in depth against admin-API
 *  misuse). */
export function getRoleForOrg(person: StoredPerson, orgId?: string | null): string {
  if (person.role === 'SUPER_ADMIN') return 'SUPER_ADMIN';
  if (!orgId || !person.orgRoles?.length) return person.role;
  const entry = person.orgRoles.find((r) => r.orgId === orgId);
  return entry?.role || person.role;
}

export function computeAccessibleOrgs(person: StoredPerson): Array<{ id: string; name: string; type: string; parentId: string | null }> {
  const organizations = getCachedOrgList();
  const allWorkingOrgs = organizations.filter((o) => WORKING_LEVELS.includes(o.type));

  // SUPER_ADMIN: everything
  if (person.role === 'SUPER_ADMIN') {
    return allWorkingOrgs.map((o) => ({ id: o.id, name: o.name, type: o.type, parentId: o.parentId ?? null }));
  }

  const computed = new Set<string>();

  // Process each assigned org
  for (const assignedOrgId of person.orgIds) {
    const assignedOrg = organizations.find((o) => o.id === assignedOrgId);
    if (!assignedOrg) continue;

    if (assignedOrg.type === 'company') {
      computed.add(assignedOrg.id);
      if (person.role === 'ORG_ADMIN') {
        for (const did of getDescendantOrgIds(assignedOrg.id)) {
          const d = organizations.find((o) => o.id === did);
          if (d && WORKING_LEVELS.includes(d.type)) computed.add(d.id);
        }
      } else {
        const childDivisions = organizations.filter((o) => o.parentId === assignedOrg.id && o.type === 'division');
        for (const div of childDivisions) computed.add(div.id);
      }
    } else if (assignedOrg.type === 'division') {
      computed.add(assignedOrg.id);
      if (person.role === 'ORG_ADMIN') {
        for (const did of getDescendantOrgIds(assignedOrg.id)) {
          const d = organizations.find((o) => o.id === did);
          if (d && WORKING_LEVELS.includes(d.type)) computed.add(d.id);
        }
      }
    } else {
      // Department/team/unit: find parent division or company
      for (const aid of getAncestorOrgs(assignedOrg.id, WORKING_LEVELS)) computed.add(aid);
    }
  }

  // Add explicit grants
  for (const grantId of person.accessibleOrgIds) {
    const org = organizations.find((o) => o.id === grantId);
    if (org && WORKING_LEVELS.includes(org.type)) computed.add(grantId);
  }

  // Deduplicate by org ID (Set guarantees uniqueness) and by name
  // in case the same org appears under different IDs
  const seen = new Set<string>();
  return Array.from(computed)
    .map((id) => {
      const org = organizations.find((o) => o.id === id);
      return org ? { id: org.id, name: org.name, type: org.type, parentId: org.parentId ?? null } : null;
    })
    .filter((o): o is { id: string; name: string; type: string; parentId: string | null } => {
      if (!o) return false;
      const key = `${o.name.toLowerCase()}|${o.type}`;
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    });
}

/**
 * Returns the full set of org IDs the authenticated user is allowed to see,
 * or `null` when the user has unrestricted access (SUPER_ADMIN, or a user
 * with no matching people record — the dev fallback).
 *
 * The visible set is derived from `computeAccessibleOrgs` and then expanded
 * to include every descendant (of any org type) under each accessible
 * working-level org. This ensures a user scoped to, e.g., "Newport News
 * Shipbuilding" cannot see sibling divisions or other unrelated companies,
 * but can still see the departments/teams/units beneath NNS.
 */
export function getVisibleOrgIds(
  user: { email?: string; role?: string } | undefined | null,
): Set<string> | null {
  if (!user) return null;
  if (user.role === 'SUPER_ADMIN') return null;

  const person = peopleSource().find(
    (p) => p.email.toLowerCase() === (user.email || '').toLowerCase(),
  );
  // No matching people record — dev fallback, unrestricted.
  if (!person) return null;
  if (person.role === 'SUPER_ADMIN') return null;

  const visible = new Set<string>();
  for (const o of computeAccessibleOrgs(person)) {
    visible.add(o.id);
    for (const descId of getDescendantOrgIds(o.id)) {
      visible.add(descId);
    }
  }
  return visible;
}

/**
 * Returns true if the user is allowed to access the given org.
 * An unrestricted user (SUPER_ADMIN / dev fallback) always passes.
 */
export function canAccessOrg(
  user: { email?: string; role?: string } | undefined | null,
  orgId: string,
): boolean {
  const visible = getVisibleOrgIds(user);
  if (visible === null) return true;
  return visible.has(orgId);
}

